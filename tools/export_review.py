"""Writes docs/content-review.md: every task of every level with its correct answer, for review.

Usage: python tools/export_review.py
"""
import json

OUT = "docs/content-review.md"
TYPE_NAMES = {
    "single_choice": "Бір жауап", "fill_blank": "Бос орын", "matching": "Сәйкестендіру",
    "chronology": "Хронология", "map": "Карта", "image": "Сурет",
}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def answer(q):
    kind = q.get("type", "single_choice")
    if kind == "matching":
        return "<br>".join("%s → %s" % (p["left"], p["right"]) for p in q["pairs"])
    if kind == "chronology":
        return " → ".join(q["items"])
    if kind == "map":
        loc = next(l for l in q["locations"] if l["name"] == q["correct"])
        others = ", ".join(l["name"] for l in q["locations"] if l["name"] != q["correct"])
        return "**%s** (%.2f° N, %.2f° E); other pins: %s" % (q["correct"], loc["lat"], loc["lon"], others)
    wrong = ", ".join(a for a in q["answers"] if a != q["correct"])
    extra = " — image: `%s`" % q["image"].replace("res://", "") if kind == "image" else ""
    if q.get("extra_answers"):
        extra += "; decoys on harder levels: %s" % ", ".join(q["extra_answers"])
    return "**%s** (wrong: %s)%s" % (q["correct"], wrong, extra)


def main():
    with open("data/levels.json", encoding="utf-8") as f:
        levels = json.load(f)["levels"]
    lines = [
        "# Question review",
        "",
        "Generated by `tools/export_review.py` from the question files — edit the JSON files, not this page.",
        "See `docs/history-review-checklist.md` for the items that most need checking.",
        "",
    ]
    for level in levels:
        path = level["question_file"].replace("res://", "")
        with open(path, encoding="utf-8") as f:
            questions = json.load(f)
        lines += ["## %d. %s (`%s`, %d tasks)" % (level["id"], level["title"], path, len(questions)), "",
                  "| ID | Type | Question | Correct answer |", "|---|---|---|---|"]
        for q in questions:
            lines.append("| %s | %s | %s | %s |" % (q["id"], TYPE_NAMES[q.get("type", "single_choice")],
                                                 cell(q["question"]), cell(answer(q))))
        lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
